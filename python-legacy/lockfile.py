"""The lockfile: ``harness.lock``.

The central artifact. It documents what the agent is and the evidence it works,
enforces what the runtime must match, and versions/diffs cleanly in git.

Schema version 1. Readers must reject unknown major versions.
"""

from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Literal

import tomllib
from pydantic import BaseModel, Field

from hlock.errors import (
    AgentLockError,
    CheckFailed,
    LockfileError,
    sha256_text,
)
from hlock.version import __version__

LOCK_VERSION = 1
HEADER = "# This file is generated by harness-lock. Do not edit by hand."


# --------------------------------------------------------------------------- #
# Component envelopes
# --------------------------------------------------------------------------- #
class LLM(BaseModel):
    role: str
    provider: str
    model: str  # never an alias; aliases resolved at lock time
    resolved_from: str | None = None
    params: dict[str, Any] = Field(default_factory=dict)
    fingerprint: str | None = None


class Decision(BaseModel):
    kind: Literal["none", "rules", "llm", "model"] = "none"
    model: str | None = None
    revision: str | None = None
    decisions: list[str] = Field(default_factory=list)
    thresholds: dict[str, float] = Field(default_factory=dict)


class Harness(BaseModel):
    name: str
    version: str | None = None
    source: str | None = None
    integrity: str | None = None
    adapter: str | None = None
    config: str | None = None  # content hash of rendered config
    pattern: str | None = None


class Tool(BaseModel):
    name: str
    kind: str = "builtin"
    source: str | None = None
    integrity: str | None = None
    tool_schema: str | None = Field(default=None, alias="schema")
    permissions: list[str] = Field(default_factory=list)

    model_config = {"populate_by_name": True}

    def serialize(self) -> dict[str, Any]:
        d = self.model_dump(by_alias=True, exclude_none=True)
        # model_dump(by_alias) yields "schema" for tool_schema
        return d


class Skill(BaseModel):
    name: str
    origin: Literal["third-party", "first-party", "bundled", "harness-builtin", "generated"] = "third-party"
    source: str | None = None
    digest: str | None = None
    registry: str | None = None
    provided_by: str | None = None
    enabled: bool = True
    editable: bool = False
    evidence_digest: str | None = None
    requires: list[str] = Field(default_factory=list)


class Instructions(BaseModel):
    name: str
    digest: str | None = None
    scope: str = "project"


class Policy(BaseModel):
    retries: int = 0
    tool_timeout_seconds: int | None = None
    max_steps: int = 40
    max_cost_usd_per_task: float | None = None
    sandbox: dict[str, Any] = Field(default_factory=dict)
    human_approval: str = "never"
    risky_actions: list[str] = Field(default_factory=list)
    tool_allowlist: list[str] = Field(default_factory=list)


class Context(BaseModel):
    isolation: Literal["locked-only", "merge-user"] = "locked-only"
    compaction: dict[str, Any] = Field(default_factory=dict)


class Evidence(BaseModel):
    task_pack: str | None = None
    task_pack_version: str | None = None
    split: str = "holdout"
    trials: int = 0
    success_rate: dict[str, Any] = Field(default_factory=dict)
    cost_usd_per_task: dict[str, Any] = Field(default_factory=dict)
    latency_s_per_task: dict[str, Any] = Field(default_factory=dict)


class Verify(BaseModel):
    canary_tasks: int = 12
    min_success_rate: float = 0.80
    fingerprint_tolerance: float = 0.15


class Provenance(BaseModel):
    backend: str = "local"
    run: str | None = None
    search: dict[str, Any] = Field(default_factory=dict)


# --------------------------------------------------------------------------- #
# Lockfile
# --------------------------------------------------------------------------- #
class Lockfile(BaseModel):
    lock_version: int = LOCK_VERSION
    generated_by: str = f"harness-lock {__version__}"
    generated_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    manifest_hash: str | None = None

    stack: dict[str, Any] = Field(default_factory=dict)
    llms: list[LLM] = Field(default_factory=list)
    decision: Decision = Field(default_factory=Decision)
    harness: Harness = Field(default_factory=Harness)
    tools: list[Tool] = Field(default_factory=list)
    skills: list[Skill] = Field(default_factory=list)
    instructions: list[Instructions] = Field(default_factory=list)
    policy: Policy = Field(default_factory=Policy)
    context: Context = Field(default_factory=Context)
    evidence: Evidence = Field(default_factory=Evidence)
    verify: Verify = Field(default_factory=Verify)
    provenance: Provenance = Field(default_factory=Provenance)

    @classmethod
    def _now(cls) -> str:
        return datetime.now(timezone.utc).isoformat()

    # ------------------------------------------------------------------ #
    # Serialization
    # ------------------------------------------------------------------ #
    @classmethod
    def load(cls, path: str | Path) -> Lockfile:
        p = Path(path)
        if not p.exists():
            raise LockfileError(f"lockfile not found: {p}")
        try:
            raw = tomllib.loads(p.read_text("utf-8"))
        except tomllib.TOMLDecodeError as e:  # pragma: no cover - defensive
            raise LockfileError(f"invalid harness.lock: {e}") from e
        return cls.from_dict(raw)

    @classmethod
    def from_dict(cls, raw: dict[str, Any]) -> Lockfile:
        try:
            version = raw.get("lock-version")
            if version != LOCK_VERSION:
                raise LockfileError(
                    f"unsupported lock-version {version!r} (this build supports {LOCK_VERSION})"
                )
            lf = cls(
                lock_version=version,
                generated_by=raw.get("generated-by", f"harness-lock {__version__}"),
                generated_at=raw.get("generated-at", cls._now()),
                manifest_hash=raw.get("manifest-hash"),
                stack=raw.get("stack", {}),
                llms=[LLM(**llm) for llm in raw.get("llm", [])],
                decision=Decision(**raw.get("decision", {})),
                harness=Harness(**raw.get("harness", {})),
                tools=[Tool(**t) for t in raw.get("tool", [])],
                skills=[Skill(**s) for s in raw.get("skill", [])],
                instructions=[Instructions(**i) for i in raw.get("instructions", [])],
                policy=Policy(**raw.get("policy", {})),
                context=Context(**raw.get("context", {})),
                evidence=Evidence(**raw.get("evidence", {})),
                verify=Verify(**raw.get("verify", {})),
                provenance=Provenance(**raw.get("provenance", {})),
            )
        except (ValueError, TypeError) as e:
            raise LockfileError(f"invalid harness.lock: {e}") from e
        return lf

    def to_dict(self) -> dict[str, Any]:
        return {
            "lock-version": self.lock_version,
            "generated-by": self.generated_by,
            "generated-at": self.generated_at,
            "manifest-hash": self.manifest_hash,
            "stack": self.stack,
            "llm": [llm.model_dump(exclude_none=True) for llm in self.llms],
            "decision": self.decision.model_dump(exclude_none=True),
            "harness": self.harness.model_dump(exclude_none=True),
            "tool": [t.serialize() for t in self.tools],
            "skill": [s.model_dump(exclude_none=True) for s in self.skills],
            "instructions": [i.model_dump(exclude_none=True) for i in self.instructions],
            "policy": self.policy.model_dump(exclude_none=True),
            "context": self.context.model_dump(exclude_none=True),
            "evidence": self.evidence.model_dump(exclude_none=True),
            "verify": self.verify.model_dump(exclude_none=True),
            "provenance": self.provenance.model_dump(exclude_none=True),
        }

    def save(self, path: str | Path) -> Path:
        p = Path(path)
        p.parent.mkdir(parents=True, exist_ok=True)
        import tomli_w

        body = tomli_w.dumps(self.to_dict())
        p.write_text(f"{HEADER}\n{body}")
        return p

    # ------------------------------------------------------------------ #
    def summary(self) -> str:
        """One-line human summary of the locked stack + evidence."""
        ev = self.evidence
        sr = ev.success_rate.get("mean", "?")
        cost = ev.cost_usd_per_task.get("mean", "?")
        model = self.llms[0].model if self.llms else "?"
        return (
            f"stack={self.stack.get('name', 'agent')!r} "
            f"harness={self.harness.name!r} llm={model!r} "
            f"decision={self.decision.kind!r} "
            f"success-rate={sr} cost={cost} trials={ev.trials}"
        )

    def check_manifest(self, manifest_hash: str | None) -> list[str]:
        """Return a list of manifest-drift violations (empty means clean)."""
        if self.manifest_hash is None:
            return ["lock has no manifest-hash"]
        if manifest_hash is None:
            return ["manifest hash unavailable"]
        pinned = self.manifest_hash.split(":", 1)[-1]
        live = sha256_text(manifest_hash) if ":" not in manifest_hash else manifest_hash.split(":", 1)[-1]
        if pinned == live:
            return []
        return [f"manifest drift: lock pinned {self.manifest_hash!r}, live {manifest_hash!r}"]

    def __repr__(self) -> str:  # pragma: no cover - cosmetic
        return f"Lockfile({self.stack.get('name', 'agent')!r}, {self.harness.name!r})"



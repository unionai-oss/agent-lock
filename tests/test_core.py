"""Tests for the manifest, lockfile, store, search, and tasks modules."""


import pytest

from hpm.errors import LockfileError, sha256_text
from hpm.lockfile import Lockfile
from hpm.manifest import Manifest
from hpm.search import Stack, StackScore, pareto_front, select_winner
from hpm.store import Store
from hpm.tasks import TaskPack
from hpm.version import __version__


# --------------------------------------------------------------------------- #
# Manifest
# --------------------------------------------------------------------------- #
def test_manifest_from_toml(tasks_pack):
    manifest = Manifest(
        project={"name": "x"},
        tasks={"packs": [str(tasks_pack)], "seeds": 2},
        candidates={"llm": {"planner": {"any_of": ["reference:qwen-7b"]}}, "harness": ["reference"]},
    )
    assert manifest.name == "x"
    assert manifest.task_packs() == [str(tasks_pack)]
    assert manifest.seeds() == 2
    assert isinstance(manifest.manifest_hash(), str)
    assert manifest.manifest_hash().startswith("sha256:")


def test_manifest_roundtrip(tmp_path):
    raw = {
        "project": {"name": "rt"},
        "tasks": {"packs": ["./tasks"], "seeds": 1},
        "candidates": {"llm": {"planner": {"any_of": ["reference:qwen-32b"]}}, "harness": ["reference"]},
        "objective": {"constraints": {"success-rate": ">=0.5"}, "select": "min-cost"},
        "backend": {"target": "local"},
    }
    p = tmp_path / "agentlock.toml"
    m = Manifest(**raw)
    # save/reload through toml-w
    m.save(p)
    m2 = Manifest.load(p)
    assert m2.project["name"] == "rt"
    assert m2.backend.target == "local"


# --------------------------------------------------------------------------- #
# Store
# --------------------------------------------------------------------------- #
def test_store_roundtrip(tmp_path):
    s = Store(tmp_path / "store")
    ref = s.put_text("hello world")
    assert ref.startswith("sha256:")
    assert s.get_text(ref) == "hello world"
    assert s.exists(ref)
    assert s.count == 1
    # write-once: same content does not grow the store
    s.put_text("hello world")
    assert s.count == 1


# --------------------------------------------------------------------------- #
# Lockfile
# --------------------------------------------------------------------------- #
def test_lockfile_roundtrip(tmp_path):
    lf = Lockfile(stack={"name": "demo"}, llms=[], decision={"kind": "none"}, harness={"name": "reference"})
    lf.manifest_hash = sha256_text("abc")
    path = tmp_path / "agent.lock"
    lf.save(path)
    assert "# This file is generated by harness-package-manager. Do not edit by hand." in path.read_text()

    lf2 = Lockfile.load(path)
    assert lf2.lock_version == 1
    assert lf2.harness.name == "reference"
    assert lf2.evidence.trials == 0
    assert lf2.generated_by == f"harness-package-manager {__version__}"
    assert lf2.check_manifest(sha256_text("abc")) == []
    assert lf2.check_manifest(sha256_text("xyz")) != []


def test_lockfile_rejects_future_major(tmp_path):
    p = tmp_path / "agent.lock"
    p.write_text("lock-version = 999\n[harness]\nname = 'x'\n")
    with pytest.raises(LockfileError):
        Lockfile.load(p)



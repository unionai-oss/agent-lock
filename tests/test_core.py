# Search / selection
# --------------------------------------------------------------------------- #
def test_pareto_and_select():
    def mk(name, sr, cost):
        s = Stack(llm={"planner": name}, harness="reference")
        return StackScore(stack=s, trials=[], success_rate=sr, cost_usd=cost, latency_s=1.0, n=3)

    cheap = mk("cheap", 0.85, 0.1)
    pricey = mk("pricey", 0.95, 1.0)
    front = pareto_front([cheap, pricey, mk("dominated", 0.5, 0.2)])
    # dominated (0.5, 0.2) is dominated by cheap (0.85, 0.1)? cheap has higher qual & <= cost -> yes
    assert any(f.stack.llm["planner"] == "cheap" for f in front)

    class Obj:
        primary = "success-rate"
        constraints = {"success-rate": ">=0.8"}
        select = "min-cost"

    winner = select_winner([cheap, pricey], Obj())
    assert winner == cheap  # min-cost among those meeting >=0.8


def test_pareto_no_constraint_hits():
    def mk(name, sr, cost):
        s = Stack(llm={"planner": name}, harness="reference")
        return StackScore(stack=s, trials=[], success_rate=sr, cost_usd=cost, latency_s=1.0, n=3)

    class Obj:
        primary = "success-rate"
        constraints = {"success-rate": ">=0.99"}  # unreachable
        select = "min-cost"

    # falls back to front (min cost) rather than crashing
    winner = select_winner([mk("a", 0.9, 0.5), mk("b", 0.8, 0.1)], Obj())
    assert winner.cost_usd == 0.1


def test_stack_hash_stable():
    a = Stack(llm={"planner": "q"}, harness="reference")
    b = Stack(llm={"planner": "q"}, harness="reference")
    assert a.hash() == b.hash()
    c = Stack(llm={"planner": "other"}, harness="reference")
    assert a.hash() != c.hash()



def test_task_pack_load_and_grade(tasks_pack, tmp_path):
    pack = TaskPack.load(str(tasks_pack))
    assert pack.name == "harness-package-manager/demo"
    assert len(pack.tasks) == 2

    task = next(t for t in pack.tasks if t.id == "summarize_report")
    assert "executive summary" in task.load_prompt_text()

    # winning workspace has the expected artifact -> passes
    ws = tmp_path / "ok"
    ws.mkdir()
    (ws / "summary.md").write_text("x")
    from hpm.traces import Trace

    trace = Trace.new("h", task.id, 0)
    trace.trial["_expected"] = {"artifacts": ["summary.md"]}
    grades = pack.grade(task, ws, trace)
    assert all(g.success for g in grades)

    # missing artifact -> fails
    ws2 = tmp_path / "missing"
    ws2.mkdir()
    grades = pack.grade(task, ws2, trace)
    assert not all(g.success for g in grades)


def test_task_pack_split_deterministic(tasks_pack):
    pack = TaskPack.load(str(tasks_pack))
    a, b = pack.split(0.7, seed=1)
    c, d = pack.split(0.7, seed=1)
    assert [t.id for t in a] == [t.id for t in c]
    assert [t.id for t in b] == [t.id for t in d]
